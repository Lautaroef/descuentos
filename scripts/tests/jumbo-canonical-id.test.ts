// =============================================================================
// 1. Cuotas tiers — 3 vs 12 on same bank+day yield distinct ids under v2
// =============================================================================

test('jumbo (P0 bug2): 3 vs 12 cuotas same bank+day yield DIFFERENT ids under v2', () => {
  const source_url = 'https://www.jumbo.com.ar/descuentos-del-dia';
  const day = dayKey([0, 1, 2, 3, 4, 5, 6]);
  const banks = banksKey(['cencopay']);
  const wallets = walletsKey([]);

  const id3 = supermarketPromoId({
    source_url,
    day_key: day,
    banks_key: banks,
    wallets_key: wallets,
    pct: 0,
    promo_type: 'cuotas',
    variant_key: variantKey({
      promo_type: 'cuotas',
      cuotas_count: 3,
      tope: null,
      tope_period: null,
    }),
  });
  const id12 = supermarketPromoId({
    source_url,
    day_key: day,
    banks_key: banks,
    wallets_key: wallets,
    pct: 0,
    promo_type: 'cuotas',
    variant_key: variantKey({
      promo_type: 'cuotas',
      cuotas_count: 12,
      tope: null,
      tope_period: null,
    }),
  });
  assert.notStrictEqual(id3, id12, 'v2: cuotas tiers distinguished');

  // And under v1, they WOULD collide — pinned in supermarket-extract.test.ts.
  const v1Shared = {
    source_url,
    day_key: day,
    bank_key: 'cencopay',
    pct: 0,
    promo_type: 'cuotas',
  };
  assert.strictEqual(
    supermarketPromoIdV1(v1Shared),
    supermarketPromoIdV1(v1Shared),
    'v1: 3 and 12 cuotas collide (bug pinned)',
  );
});

// =============================================================================
// 2. Multi-bank promos — different bank compositions with shared primary
//    yield different ids under v2 (v1 would collide)
// =============================================================================

test('carrefour (P0 bug2): multi-bank promos with shared primary yield DIFFERENT ids under v2', () => {
  const source_url = 'https://www.carrefour.com.ar/descuentos-bancarios';
  const day = dayKey([6]);
  const pct = 10;

  const aV2 = supermarketPromoId({
    source_url,
    day_key: day,
    banks_key: banksKey(['bbva', 'galicia']),
    wallets_key: walletsKey([]),
    pct,
    promo_type: 'cashback',
    variant_key: '',
  });
  const bV2 = supermarketPromoId({
    source_url,
    day_key: day,
    banks_key: banksKey(['bbva', 'santander']),
    wallets_key: walletsKey([]),
    pct,
    promo_type: 'cashback',
    variant_key: '',
  });
  assert.notStrictEqual(aV2, bV2, 'v2 distinguishes bank compositions');

  // v1: primaryBank([bbva, galicia]) === primaryBank([bbva, santander]) === 'bbva'
  const aV1 = supermarketPromoIdV1({
    source_url,
    day_key: day,
    bank_key: 'bbva',
    pct,
    promo_type: 'cashback',
  });
  const bV1 = supermarketPromoIdV1({
    source_url,
    day_key: day,
    bank_key: 'bbva',
    pct,
    promo_type: 'cashback',
  });
  assert.strictEqual(aV1, bV1, 'v1 would collide on multi-bank promos (bug pinned)');
});

