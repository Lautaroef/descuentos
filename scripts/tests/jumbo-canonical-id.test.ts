// P0 regression — Jumbo canonical-id v2.
//
// Context (2026-04-23): `pnpm run-jumbo` reported 30 inserted / 47 updated but
// the DB held only 14 distinct rows for source_id='jumbo-descuentos'. Root
// cause: the v1 id tuple (source_url, day_key, bank_key, pct, promo_type)
// collapsed multiple cuotas tiers on the same bank/day to the same id. The
// Cencopay block (3/6/12/18/24 cuotas all on "Todos los días") collapses
// 5 distinct promos into 1 row. The same applies to Galicia, Santander,
// Naranja X, and Comafi on the live page.
//
// Fix: the v2 tuple adds `variant_key` (cuotas_count for cuotas rows). These
// tests verify:
//
//   1. Two distinct cuotas tiers (3 vs 12) on same bank+day produce DIFFERENT
//      ids under v2.
//   2. Under v1 they would have collided (pinned by the v1 regression test
//      in supermarket-extract.test.ts).
//   3. Carrefour multi-bank promos with different bank compositions but
//      shared primary bank produce DIFFERENT ids under v2.
//   4. The cross-wallet universal block's ids don't collide with single-
//      wallet variants of the same pct/day.
//   5. Every id generated by the extractor from a realistic Jumbo payload
//      is unique (≥20 rows, zero intra-run collisions).
//   6. Existing idempotency of the extractor is preserved.
