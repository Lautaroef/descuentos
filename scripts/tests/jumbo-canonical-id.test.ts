// =============================================================================
// 5. Idempotency: two back-to-back runs with identical input → identical ids
// =============================================================================

test('jumbo: canonical-id v2 is stable across identical runs', async () => {
  const raw = await readFile(resolve(FIX_JUMBO, 'descuentos-del-dia.extract.json'), 'utf8');
  const fx = JSON.parse(raw) as { source_url: string; data: { promos: any[] } };
  const stub = async () => ({ data: { promos: fx.data.promos }, usage: usage() });

  const run1 = await extractJumboPromos({ source_url: fx.source_url, markdown: 'md', llmOverride: stub });
  const run2 = await extractJumboPromos({ source_url: fx.source_url, markdown: 'md', llmOverride: stub });
  assert.deepStrictEqual(run1.ids, run2.ids);
});

